
// While Loop   - Another syntatcical way of writing for loop 

// Probelem Statement- Print all the multiples of 5 till 100


#include <iostream>
using namespace std;

int main() {

  int i = 5;

  while (i <= 100) {
    cout << i << endl;

    i = i + 5;
  }
    cout << i;
    return 0;
}


